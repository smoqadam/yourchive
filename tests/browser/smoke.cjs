const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 async function until(predicate){for(let n=0;n<100;n++){if(await page.evaluate(predicate))return;await new Promise(r=>setTimeout(r,100));}throw Error('Timed out waiting for UI state');}
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const url=process.env.BASE_URL||'http://qa:8000';
 await page.goto(url);await page.waitForSelector('.video-card');
 assert.equal(await page.locator('.video-card').count(),3);
 await page.screenshot({path:'artifacts/library-desktop.png',fullPage:true,animations:"disabled"});
 await page.locator('#search').fill('quiet');assert.equal(await page.locator('.video-card').count(),1);
 await page.locator('[data-favorite="fixture0001"]').click();
 await until(()=>document.querySelector('[data-favorite="fixture0001"]').getAttribute('aria-pressed')==='true');
 await page.locator('[data-view="favorites"]').click();assert.equal(await page.locator('.video-card').count(),1);
 await page.locator('.thumbnail').click();await page.waitForSelector('#video-player');
 await until(()=>document.querySelector('#video-player').readyState>=1);
 assert.equal(await page.locator('track').count(),1);
 await page.locator('#video-player').evaluate(v=>{v.currentTime=4;});
 await page.locator('[data-action="toggle-watched"]').click();
 await page.locator('[data-action="close-player"]').click();
 await until(()=>!document.querySelector('#player-dialog').open);
 await page.locator('[data-view="channels"]').click();assert.equal(await page.locator('.group-card').count(),2);
 await page.locator('[data-group="UCfixture1"]').click();assert.equal(await page.locator('.video-card').count(),1);
 await page.locator('[data-view="playlists"]').click();await page.locator('.group-card').click();assert.equal(await page.locator('.video-card').count(),3);
 await page.locator('[data-view="settings"]').click();await page.waitForSelector('#settings-form');
 await page.locator('#settings-quality').selectOption('720');await page.locator('#settings-languages').fill('en,de');
 await page.locator('button[type="submit"]:visible').click();await until(()=>document.querySelector('#toast').textContent==='Preferences saved.');
 await page.locator('#add-button').click();await page.waitForSelector('#source-url');
 assert.equal(await page.locator('#download-quality').inputValue(),'720');
 await page.locator('#source-url').fill('https://example.com/video');
 await page.locator('#add-form button[type="submit"]').click();await until(()=>document.querySelector('#add-error').textContent.includes('YouTube'));
 await page.screenshot({path:'artifacts/add-dialog.png',fullPage:true,animations:"disabled"});
 await page.locator('#add-form button.close-dialog').first().click();
 await page.locator('[data-view="library"]').click();await page.locator('[data-layout="list"]').click();assert.equal(await page.locator('.list-view').count(),1);
 await page.locator('[data-layout="grid"]').click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'artifacts/library-mobile.png',fullPage:true,animations:"disabled"});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows');
 await page.locator('#menu-toggle').click();await page.locator('[data-view="downloads"]').click();
 assert.equal(await page.locator('.empty-state').count(),1);
 await page.setViewportSize({width:1440,height:1080});
 await page.locator('[data-view="library"]').click();await page.locator('[data-play="fixture0001"]').first().click();
 await page.locator('[data-action="delete-video"]').click();await page.locator('#confirm-dialog button[value="delete"]').click();
 await until(()=>!document.querySelector('#player-dialog').open);
 await until(()=>document.querySelectorAll('.video-card').length===2);
 assert.deepEqual(errors,[]);
 console.log('Browser checks passed: library, search, favorites, playback, captions, progress, channels, playlists, preferences, validation, views, mobile layout, deletion.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
